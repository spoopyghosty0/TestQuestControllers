#!/usr/bin/env python3
"""Generates app/src/main/cpp/profiles_gen.inc, the table of Quest controller types, from the OpenXR registry.

    python3 tools/gen_profiles.py [--xml xr.xml] [--check]

Without --xml the registry is downloaded from OpenXR-Docs at REGISTRY_COMMIT. --check fails if the committed file
differs from what would be generated.
"""
import argparse
import sys
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "app/src/main/cpp/profiles_gen.inc"
REGISTRY_COMMIT = "18ebc0374da23c020ef4c949f9b144ffae6160ef"
REGISTRY_URL = (f"https://raw.githubusercontent.com/KhronosGroup/OpenXR-Docs/{REGISTRY_COMMIT}"
                "/specification/registry/xr.xml")

# Menu entries in display order: (profile path, label, model = WebXR Input Profiles id, see fetch_models.py)
ENTRIES = [
    ("/interaction_profiles/oculus/touch_controller", "Touch (most Quest games)", "oculus-touch-v3"),
    ("/interaction_profiles/meta/touch_controller_plus", "Touch Plus (Quest 3/3S)", "meta-quest-touch-plus-v2"),
    ("/interaction_profiles/facebook/touch_controller_pro", "Touch Pro (Quest Pro)", "meta-quest-touch-pro"),
    ("/interaction_profiles/oculus/go_controller", "Oculus Go controller", "oculus-go"),
    ("/interaction_profiles/meta/touch_controller_quest_2", "Quest 2 Touch (OpenXR 1.1)", "oculus-touch-v3"),
    ("/interaction_profiles/meta/touch_controller_quest_1_rift_s", "Quest 1 / Rift S Touch (OpenXR 1.1)", "oculus-touch-v2"),
    ("/interaction_profiles/meta/touch_controller_rift_cv1", "Rift CV1 Touch (OpenXR 1.1)", "oculus-touch"),
    ("/interaction_profiles/meta/touch_plus_controller", "Touch Plus (OpenXR 1.1)", "meta-quest-touch-plus-v2"),
    ("/interaction_profiles/meta/touch_pro_controller", "Touch Pro (OpenXR 1.1)", "meta-quest-touch-pro"),
]
# Extensions whose extra inputs on a profile are bound when the runtime offers them
OPTIONAL_EXTENSIONS = {"XR_FB_touch_controller_proximity"}
TYPES = {
    "XR_ACTION_TYPE_BOOLEAN_INPUT": "XR_ACTION_TYPE_BOOLEAN_INPUT",
    "XR_ACTION_TYPE_FLOAT_INPUT": "XR_ACTION_TYPE_FLOAT_INPUT",
    "XR_ACTION_TYPE_VECTOR2F_INPUT": "XR_ACTION_TYPE_VECTOR2F_INPUT",
    "XR_ACTION_TYPE_POSE_INPUT": "XR_ACTION_TYPE_POSE_INPUT",
    "XR_ACTION_TYPE_VIBRATION_OUTPUT": "XR_ACTION_TYPE_VIBRATION_OUTPUT",
}
SKIP_SUFFIXES = ("/grip_surface/pose", "/palm_ext/pose")


def load(xml_path):
    if xml_path:
        return ET.parse(xml_path).getroot()
    with urllib.request.urlopen(REGISTRY_URL, timeout=60) as resp:
        return ET.fromstring(resp.read())


def components(elem, user_paths):
    """[(user path or None for every hand, subpath, type, system)] of one profile or extend element."""
    found = []
    for c in elem.findall("component"):
        sub = c.get("subpath")
        if sub.endswith(SKIP_SUFFIXES):
            continue
        parent = sub.rsplit("/", 1)[0]
        # thumbstick/x and /y repeat the vector input; bind the vector only
        if sub.endswith(("/x", "/y")) and any(o.get("subpath") == parent for o in elem.findall("component")):
            continue
        found.append((c.get("user_path"), sub, TYPES[c.get("type")], c.get("system") == "true"))
    return found


def generate(root):
    defs = {p.get("name"): p for p in root.iter("interaction_profile") if p.find("component") is not None}
    provider = {}   # profile -> ("ext", name) or ("version", minor)
    extends = {}    # profile -> [(extension, components)]
    for feature in root.iter("feature"):
        minor = int(feature.get("number", "1.0").split(".")[1])
        for ref in feature.iter("interaction_profile"):
            if ref.find("component") is None:
                provider.setdefault(ref.get("name"), ("version", minor))
    for ext in root.iter("extension"):
        name = ext.get("name")
        for req in ext.findall("require"):
            for ref in req.findall("interaction_profile"):
                provider.setdefault(ref.get("name"), ("ext", name))
            if name in OPTIONAL_EXTENSIONS and not req.get("depends"):
                for ex in req.findall("extend"):
                    extends.setdefault(ex.get("interaction_profile_path"), []).append((name, ex))

    lines = [
        "// Generated by tools/gen_profiles.py from the OpenXR registry (xr.xml) at OpenXR-Docs",
        f"// {REGISTRY_COMMIT}. Do not edit.",
        "",
    ]
    table = []
    for i, (path, label, family) in enumerate(ENTRIES):
        prof = defs[path]
        users = [u.get("path") for u in prof.findall("user_path")]
        kind, value = provider[path]
        ext = value if kind == "ext" else None
        minor = value if kind == "version" else 0
        rows = [(u, s, t, sysflag, None) for u, s, t, sysflag in components(prof, users)]
        for ext_name, ex in extends.get(path, []):
            rows += [(u, s, t, sysflag, ext_name) for u, s, t, sysflag in components(ex, users)]
        lines.append(f"static const Component kComponents{i}[] = {{")
        for u, s, t, sysflag, req in rows:
            hand = {"/user/hand/left": "kLeft", "/user/hand/right": "kRight", None: "kBoth"}[u]
            req_s = f'"{req}"' if req else "nullptr"
            lines.append(f'    {{{hand}, "{s}", {t}, {"true" if sysflag else "false"}, {req_s}}},')
        lines.append("};")
        ext_s = f'"{ext}"' if ext else "nullptr"
        table.append(f'    {{"{path}", "{label}", "{prof.get("title")}", {ext_s}, {minor}, "{family}", '
                     f"kComponents{i}, {len(rows)}}},")
    lines.append("")
    lines.append("static const Profile kProfiles[] = {")
    lines += table
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--xml")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = generate(load(args.xml))
    if args.check:
        if OUT.read_text() != text:
            sys.exit(f"{OUT} is out of date: run tools/gen_profiles.py")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
